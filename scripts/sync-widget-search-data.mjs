/**
 * Sync static search data from src/data/* into WordPress widget HTML files.
 * Run: node scripts/sync-widget-search-data.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");

function read(file) {
  return fs.readFileSync(path.join(root, file), "utf8");
}

function extractArrayExport(source, exportName) {
  const re = new RegExp(`export const ${exportName}[^=]*=\\s*(\\[[\\s\\S]*?\\]);`);
  const m = source.match(re);
  if (!m) throw new Error(`Could not parse ${exportName}`);
  // eslint-disable-next-line no-eval
  return eval(`(${m[1]})`);
}

function extractCoordsRecord(source) {
  const re = /export const STAY_DESTINATION_COORDS[^=]*=\s*(\{[\s\S]*?\n\});/;
  const m = source.match(re);
  if (!m) throw new Error("Could not parse STAY_DESTINATION_COORDS");
  // eslint-disable-next-line no-eval
  return eval(`(${m[1]})`);
}

const airports = extractArrayExport(read("src/data/airports.ts"), "AIRPORTS");
const destinations = extractArrayExport(read("src/data/destinations.ts"), "DESTINATIONS");
const carLocations = extractArrayExport(read("src/data/locations.ts"), "CAR_LOCATIONS");
const stayCoords = extractCoordsRecord(read("src/data/stay-destination-coords.ts"));

const dataBlock = `      // AUTO-GENERATED by scripts/sync-widget-search-data.mjs — do not edit manually
      const AIRPORTS = ${JSON.stringify(airports, null, 2)};
      const DESTINATIONS = ${JSON.stringify(destinations, null, 2)};
      const CAR_LOCATIONS = ${JSON.stringify(carLocations, null, 2)};
      const STAY_DESTINATION_COORDS = ${JSON.stringify(stayCoords, null, 2)};
`;

const markerStart = "      // AUTO-GENERATED by scripts/sync-widget-search-data.mjs";
const markerEnd = "      // END AUTO-GENERATED widget data";

const targets = [
  "z-docs/docs/wordpress/ttu-travel-search-widget-embed.html",
  "z-docs/docs/wordpress/ttu-travel-search-widget.html",
];

for (const rel of targets) {
  const filePath = path.join(root, rel);
  let html = read(rel);
  const startIdx = html.indexOf(markerStart);
  const endIdx = html.indexOf(markerEnd);
  if (startIdx === -1 || endIdx === -1) {
    console.warn(`Skip ${rel}: markers not found`);
    continue;
  }
  const before = html.slice(0, startIdx);
  const after = html.slice(endIdx);
  html = before + dataBlock + "\n" + after;
  fs.writeFileSync(filePath, html, "utf8");
  console.log(`Updated ${rel}`);
}
